"""Write the legacy-backend game.toml for the P3 scaffold from the P0 map.

    py -3 -I port/tools/legacy_config.py ROM --map runs/cdl/prgmap.bin --tables runs/cdl/tables.json \
        --extra runs/cdl/extra.json --base port/scaffold/game.base.toml --out port/scaffold/game.toml

The legacy recompiler discovers functions on its own and, left alone, decodes
much of the data as code. This hands it what the map already proves:

- [[extra_func]]: vectors, every JSR/JMP target of known code, the targets of
  the recognised pointer tables (object behaviours included), up to 4,096;
- [[data_region]]: the 256 longest runs of bytes the map proves are data
  (read as data, table, pointer, padding), never "unseen" bytes, which may
  hide code no run reached.

Banks are the legacy layout's 16 KiB banks: bank b holds 8 KiB banks 2b
($8000-$9FFF) and 2b+1 ($A000-$BFFF); bank 7 is the fixed $C000-$FFFF.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "tools"))
from cdl_report import CLASSES, LENGTH, OFFICIAL, resolve, window  # noqa: E402

CODE = {CLASSES.index("opcode"), CLASSES.index("code?")}
DATA = {CLASSES.index(k) for k in ("data", "table", "ptr", "fill", "pcm")}


def legacy(off):
    """PRG offset -> (legacy 16 KiB bank, CPU address in the legacy layout)."""
    b8 = off // 0x2000
    if b8 >= 0x0E:
        return 7, 0xC000 + (b8 - 0x0E) * 0x2000 + off % 0x2000
    return b8 >> 1, 0x8000 + (b8 & 1) * 0x2000 + off % 0x2000


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rom")
    ap.add_argument("--map", required=True)
    ap.add_argument("--tables", required=True)
    ap.add_argument("--extra", required=True)
    ap.add_argument("--base", required=True, help="hand-written part ([game], replace_func, ...)")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    rom = open(a.rom, "rb").read()
    prg = rom[16:16 + rom[4] * 0x4000]
    kind = open(a.map, "rb").read()
    n = len(prg)

    starts = set()
    v = prg[n - 6:]                                          # NMI, RESET, IRQ at $FFFA-$FFFF
    for k in (0, 2, 4):
        addr = v[k] | v[k + 1] << 8
        starts.add(0x0E * 0x2000 + (addr - 0xC000) if addr < 0xE000 else 0x0F * 0x2000 + (addr - 0xE000))
    for off in range(n):
        if kind[off] in CODE and prg[off] in (0x20, 0x4C) and off + 2 < n:
            t = resolve(off // 0x2000, prg[off + 1] | prg[off + 2] << 8)
            if t is not None and kind[t] in CODE:
                starts.add(t)
    for t in json.load(open(a.tables)):
        if t["type"] == "split":
            for k in range(t["count"]):
                w = (prg[t["lo"] + k] | prg[t["hi"] + k] << 8) + t["plus"]
                ctx = t["target_banks"][k] if "target_banks" in t else t["lo"] // 0x2000
                if 0xA000 <= w < 0xC000 and "target_banks" in t:
                    o = ctx * 0x2000 + (w - 0xA000)
                else:
                    o = resolve(ctx, w)
                if o is not None and kind[o] in CODE:
                    starts.add(o)
        else:
            for k in range(t["count"]):
                o = t["start"] + 2 * k
                tt = resolve(o // 0x2000, (prg[o] | prg[o + 1] << 8) + t["plus"])
                if tt is not None and kind[tt] in CODE:
                    starts.add(tt)
    starts |= {o for o in json.load(open(a.extra))["starts"] if kind[o] in CODE}
    starts.add(0x0E * 0x2000 + (0xC556 - 0xC000))          # main_task (entry via $93/$94)

    runs, i = [], 0
    while i < n:
        if kind[i] in DATA:
            j = i
            while j < n and kind[j] in DATA and j // 0x2000 == i // 0x2000:
                j += 1
            runs.append((j - i, i, j - 1))
            i = j
        else:
            i += 1
    runs.sort(reverse=True)
    picked = sorted(runs[:256], key=lambda r: r[1])

    out = [open(a.base, encoding="utf-8").read().rstrip(), "",
           "# ---- generated by port/tools/legacy_config.py from the P0 map; do not edit below ----", ""]
    for off in sorted(starts)[:4096]:
        b, addr = legacy(off)
        out += ["[[extra_func]]", f"bank = {b}", f"addr = 0x{addr:04X}", ""]
    for size, s, e in picked:
        b, sa = legacy(s)
        _, ea = legacy(e)
        out += [f"[[data_region]]  # {size} bytes", f"bank = {b}", f"start = 0x{sa:04X}", f"end = 0x{ea:04X}", ""]
    open(a.out, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    covered = sum(r[0] for r in picked)
    total = sum(r[0] for r in runs)
    print(f"{len(starts)} function starts, {len(picked)} data regions covering {covered} of {total} proven data bytes -> {a.out}")


if __name__ == "__main__":
    main()
